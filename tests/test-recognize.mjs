/** Deep walk that surfaces any undefined value (JSON.stringify would hide them). */
function assertNoUndefined(value, label) {
  const seen = new Set();
  const walk = (node, trail) => {
    if (node === undefined) throw new Error(`${label}: undefined at ${trail}`);
    if (typeof node === 'number') {
      assert.ok(Number.isFinite(node), `${label}: non-finite number at ${trail} (${node})`);
      return;
    }
    if (node === null || typeof node !== 'object') return;
    if (seen.has(node)) return;
    seen.add(node);
    if (Array.isArray(node)) {
      node.forEach((item, i) => walk(item, `${trail}[${i}]`));
      return;
    }
    for (const key of Object.keys(node)) walk(node[key], trail ? `${trail}.${key}` : key);
  };
  walk(value, '');
  assert.ok(!JSON.stringify(value).includes('undefined'), `${label}: JSON contains "undefined"`);
}
function warningCodes(recognition) {
  return (recognition.warnings || []).map((w) => w.code);
}
function isEmptyValue(value) {
  return value === null || value === undefined || value === '' || (Array.isArray(value) && value.length === 0);
}
function readPathValue(obj, dotted) {
  return dotted.split('.').reduce((acc, key) => (acc && typeof acc === 'object' ? acc[key] : undefined), obj);
}

