  function extractJsonText(value) {
    var out = { text: '', tables: [], warnings: [] };
    var lines = [];
    var tables = [];
    if (value === null || value === undefined) return out;

    function pushObjectArray(arr, prefix) {
      var keys = [];
      arr.forEach(function (obj) {
        Object.keys(obj).forEach(function (k) { if (keys.indexOf(k) < 0) keys.push(k); });
      });
      if (!keys.length) return;
      var rows = [keys.map(function (k) { return prettyKey(k) || k; })];
      arr.forEach(function (obj) {
        rows.push(keys.map(function (k) { return jsonScalar(obj[k]); }));
      });
      tables.push(rows);
      rows.forEach(function (row) { lines.push(row.join('\t')); });
    }

    function walk(node, depth) {
      if (depth > 6) return;
      if (Array.isArray(node)) {
        if (!node.length) return;
        var allObjects = true;
        var allArrays = true;
        var allScalars = true;
        node.forEach(function (item) {
          if (!(isPlainObject(item))) allObjects = false;
          if (!Array.isArray(item)) allArrays = false;
          if (isPlainObject(item) || Array.isArray(item)) allScalars = false;
        });
        if (allObjects) { pushObjectArray(node); return; }
        if (allArrays) {
          var rows = node.map(function (item) { return item.map(jsonScalar); });
          tables.push(rows);
          rows.forEach(function (row) { lines.push(row.join('\t')); });
          return;
        }
        if (allScalars) {
          var rows2 = [['Value']];
          node.forEach(function (item) { rows2.push([jsonScalar(item)]); });
          tables.push(rows2);
          rows2.forEach(function (row) { lines.push(row.join('\t')); });
          return;
        }
        node.forEach(function (item, index) { walk(item, depth + 1); });
        return;
      }
      if (isPlainObject(node)) {
        var keys = Object.keys(node);
        keys.forEach(function (key) {
          var val = node[key];
          var lowered = key.toLowerCase();
          if ((lowered === 'buyer' || lowered === 'seller') && isPlainObject(val)) {
            var labelFor = lowered === 'buyer' ? PARTY_LABELS : {
              nameEn: 'Seller', nameCn: 'Seller Chinese Name', addressEn: 'Seller Address',
              addressCn: 'Seller Chinese Address', country: 'Seller Country',
              contact: 'Seller Contact', tel: 'Seller Tel', email: 'Seller Email', taxId: 'Seller Tax ID'
            };
            var nameKey = val.nameEn !== undefined && val.nameEn !== null && val.nameEn !== '' ? 'nameEn'
              : (val.nameCn !== undefined && val.nameCn !== null && val.nameCn !== '' ? 'nameCn' : '');
            if (nameKey) lines.push(labelFor[nameKey] + ': ' + jsonScalar(val[nameKey]));
            Object.keys(val).forEach(function (field) {
              if (field === nameKey) return;
              var label = labelFor[field] || prettyKey(field);
              if (label) lines.push(label + ': ' + jsonScalar(val[field]));
            });
            return;
          }
          if (lowered === 'charges' && isPlainObject(val)) {
            Object.keys(val).forEach(function (field) {
              lines.push(prettyKey(field) + ': ' + jsonScalar(val[field]));
            });
            return;
          }
          if (isPlainObject(val) || Array.isArray(val)) {
            walk(val, depth + 1);
            return;
          }
          var label2 = prettyKey(key);
          if (label2) lines.push(label2 + ': ' + jsonScalar(val));
        });
        return;
      }
      lines.push(jsonScalar(node));
    }

    walk(value, 0);
    out.text = lines.join('\n');
    out.tables = tables;
    return out;
  }

  function markdownTables(text) {
    var lines = asString(text).split('\n');
    var tables = [];
    var i = 0;
    while (i < lines.length - 1) {
      var line = lines[i];
      var next = lines[i + 1];
      if (line.indexOf('|') >= 0 && /^\s*\|?\s*:?-{2,}/.test(next) && next.indexOf('|') >= 0) {
        var rows = [splitPipeRow(line)];
        var j = i + 2;
        while (j < lines.length && lines[j].trim() && lines[j].indexOf('|') >= 0) {
          rows.push(splitPipeRow(lines[j]));
          j++;
        }
        if (rows.length > 1) tables.push(rows);
        i = j;
        continue;
      }
      i++;
    }
    return tables;
  }

  function splitPipeRow(line) {
    var s = asString(line).trim();
    if (s.charAt(0) === '|') s = s.slice(1);
    if (s.charAt(s.length - 1) === '|') s = s.slice(0, -1);
    return s.split('|').map(function (cell) { return collapseSpaces(cell); });
  }

