  function buildLabelSource(alternatives) {
    var alt = '(?:' + alternatives.join('|') + ')';
    return alt + '(?:\\s*[\\/／|]\\s*' + alt + ')?';
  }

  function buildColonRegex(alternatives) {
    var label = buildLabelSource(alternatives);
    return new RegExp('^\\s*(?:[-*•·+>]\\s*)?(?:\\d{1,2}\\s*[.)、]\\s*)?' + label + '\\s*[:：]\\s*(.*)$', 'i');
  }

  function buildExactRegex(alternatives) {
    var label = buildLabelSource(alternatives);
    return new RegExp('^\\s*' + label + '\\s*[:：]?\\s*$', 'i');
  }

  function makeRule(field, type, confidence, labels, options) {
    var opts = options || {};
    var rule = {
      field: field,
      type: type,
      conf: confidence,
      labels: labels,
      continuation: opts.continuation === true
    };
    rule._colon = buildColonRegex(labels);
    rule._exact = buildExactRegex(labels);
    return rule;
  }

