  function parseSharedStringsXml(xml) {
    var list = [];
    if (!xml) return list;
    var re = /<si\b[^>]*>([\s\S]*?)<\/si>/g;
    var m;
    while ((m = re.exec(xml))) {
      var si = m[1];
      var text = '';
      var tRe = /<t\b[^>]*>([\s\S]*?)<\/t>|<t\b[^>]*\/>/g;
      var tm;
      while ((tm = tRe.exec(si))) {
        if (tm[1] !== undefined) text += decodeEntities(tm[1]);
      }
      list.push(text);
    }
    return list;
  }

  function parseWorkbookSheetsXml(xml) {
    var sheets = [];
    if (!xml) return sheets;
    var re = /<sheet\b([^>]*?)\/?>/g;
    var m;
    while ((m = re.exec(xml))) {
      var attrs = m[1] || '';
      var name = xmlAttr(attrs, 'name');
      var rid = xmlAttr(attrs, 'r:id');
      if (!name) continue;
      sheets.push({ name: name, rid: rid });
    }
    return sheets;
  }

  function parseRelationshipsXml(xml) {
    var map = {};
    if (!xml) return map;
    var re = /<Relationship\b([^>]*?)\/?>/g;
    var m;
    while ((m = re.exec(xml))) {
      var attrs = m[1] || '';
      var id = xmlAttr(attrs, 'Id');
      var target = xmlAttr(attrs, 'Target');
      if (id && target) map[id] = target;
    }
    return map;
  }

  function normalizeZipPath(path) {
    var parts = asString(path).replace(/\\/g, '/').split('/');
    var stack = [];
    parts.forEach(function (part) {
      if (!part || part === '.') return;
      if (part === '..') stack.pop();
      else stack.push(part);
    });
    return stack.join('/');
  }

  function resolveSheetPath(target) {
    var t = asString(target).replace(/\\/g, '/');
    if (!t) return '';
    if (t.charAt(0) === '/') return normalizeZipPath(t.slice(1));
    if (/^xl\//.test(t)) return normalizeZipPath(t);
    return normalizeZipPath('xl/' + t);
  }

  function columnIndexFromRef(ref) {
    var m = /^([A-Z]+)/i.exec(asString(ref));
    if (!m) return -1;
    var letters = m[1].toUpperCase();
    var index = 0;
    for (var i = 0; i < letters.length; i++) index = index * 26 + (letters.charCodeAt(i) - 64);
    return index - 1;
  }

  function sheetTagText(inner, tag) {
    var re = new RegExp('<' + tag + '\\b[^>]*>([\\s\\S]*?)<\\/' + tag + '>', 'i');
    var m = re.exec(inner);
    return m ? decodeEntities(m[1]) : '';
  }

  function sheetAllText(inner) {
    var text = '';
    var re = /<t\b[^>]*>([\s\S]*?)<\/t>/g;
    var m;
    while ((m = re.exec(inner))) text += decodeEntities(m[1]);
    return text;
  }

  function parseSheetRowsXml(xml, sharedStrings) {
    var rows = [];
    if (!xml) return rows;
    var prevRowNum = 0;
    var rowRe = /<row\b([^>]*?)(?:\/>|>([\s\S]*?)<\/row>)/g;
    var rowMatch;
    while ((rowMatch = rowRe.exec(xml))) {
      var rowAttrs = rowMatch[1] || '';
      var rowInner = rowMatch[2] || '';
      var rowNum = parseInt(xmlAttr(rowAttrs, 'r'), 10);
      if (Number.isFinite(rowNum) && prevRowNum && rowNum > prevRowNum + 1) rows.push([]);
      if (Number.isFinite(rowNum)) prevRowNum = rowNum;
      var cells = [];
      var cellRe = /<c\b([^>]*?)(?:\/>|>([\s\S]*?)<\/c>)/g;
      var cellMatch;
      while ((cellMatch = cellRe.exec(rowInner))) {
        var cellAttrs = cellMatch[1] || '';
        var cellInner = cellMatch[2] || '';
        var type = asString(xmlAttr(cellAttrs, 't')).toLowerCase();
        var ref = xmlAttr(cellAttrs, 'r');
        var colIdx = ref ? columnIndexFromRef(ref) : cells.length;
        if (colIdx < 0) colIdx = cells.length;
        var value = '';
        if (type === 's') {
          var idx = parseInt(sheetTagText(cellInner, 'v'), 10);
          if (Number.isFinite(idx) && sharedStrings[idx] !== undefined) value = sharedStrings[idx];
        } else if (type === 'inlinestr') {
          value = sheetAllText(cellInner);
        } else if (type === 'b') {
          value = sheetTagText(cellInner, 'v') === '1' ? 'TRUE' : 'FALSE';
        } else {
          value = sheetTagText(cellInner, 'v');
          if (type === 'e') value = value || '#ERROR';
        }
        cells[colIdx] = value;
      }
      var width = 0;
      for (var i = 0; i < cells.length; i++) if (cells[i] !== undefined) width = i + 1;
      var arr = [];
      for (var j = 0; j < width; j++) arr.push(cells[j] === undefined ? '' : asString(cells[j]));
      rows.push(arr.length ? arr : []);
    }
    while (rows.length && rows[rows.length - 1].length === 0) rows.pop();
    return rows;
  }

  async function extractXlsxText(bytes) {
    var out = { text: '', tables: [], warnings: [] };
    function warn(code, message) { out.warnings.push({ code: code, message: message }); }
    if (!bytes || bytes.length < 22) {
      warn('xlsx-invalid', '无法读取 Excel 文件：内容为空或已损坏。');
      return out;
    }
    var zip = readZipDirectory(bytes);
    out.warnings = out.warnings.concat(zip.warnings);
    if (!zip.entries.length) {
      if (!out.warnings.length) warn('xlsx-invalid', 'Excel 文件结构无效，无法解析。');
      return out;
    }

    async function entryText(path) {
      var entry = findZipEntry(zip.entries, path);
      if (!entry) return '';
      try {
        var data = await readZipEntry(bytes, entry);
        return decodeText(data);
      } catch (e) {
        warn('xlsx-invalid', '读取 ' + path + ' 失败：' + (e && e.message ? e.message : '未知错误'));
        return '';
      }
    }

    var sharedXml = await entryText('xl/sharedStrings.xml');
    var sharedStrings = parseSharedStringsXml(sharedXml);
    var workbookXml = await entryText('xl/workbook.xml');
    var relsXml = await entryText('xl/_rels/workbook.xml.rels');
    var rels = parseRelationshipsXml(relsXml);
    var sheets = parseWorkbookSheetsXml(workbookXml);
    if (!sheets.length) {
      var fallback = [];
      zip.entries.forEach(function (entry) {
        var m = /^xl\/worksheets\/(sheet\d+)\.xml$/i.exec(entry.name);
        if (m) fallback.push({ name: m[1], rid: '', sortKey: parseInt(m[1].replace(/\D+/g, ''), 10) || 0 });
      });
      fallback.sort(function (a, b) { return a.sortKey - b.sortKey; });
      sheets = fallback.map(function (s) { return { name: s.name, rid: '' }; });
      if (!sheets.length) {
        warn('xlsx-invalid', 'Excel 文件中没有可读取的工作表。');
        return out;
      }
      warn('xlsx-partial', '未能读取工作簿结构，已按默认顺序解析工作表。');
    }

    var textParts = [];
    var tableRows = [];
    var totalRows = 0;
    var sheetLimit = Math.min(sheets.length, 50);
    for (var s = 0; s < sheetLimit; s++) {
      var sheet = sheets[s];
      var target = sheet.rid && rels[sheet.rid] ? rels[sheet.rid] : ('worksheets/sheet' + (s + 1) + '.xml');
      var sheetPath = resolveSheetPath(target);
      var sheetXml = await entryText(sheetPath);
      if (!sheetXml) {
        var fallbackPath = 'xl/worksheets/sheet' + (s + 1) + '.xml';
        if (sheetPath !== fallbackPath) sheetXml = await entryText(fallbackPath);
      }
      if (!sheetXml) {
        warn('xlsx-partial', '工作表“' + sheet.name + '”读取失败。');
        continue;
      }
      var rows = parseSheetRowsXml(sheetXml, sharedStrings);
      if (!rows.length) continue;
      totalRows += rows.length;
      if (totalRows > 100000) {
        warn('xlsx-too-large', 'Excel 表格行数过多，已截断解析。');
        break;
      }
      var tsvLines = rows.map(function (row) { return row.join('\t'); });
      textParts.push('## Sheet: ' + sheet.name + '\n' + tsvLines.join('\n'));
      if (tableRows.length) tableRows.push([]);
      for (var r = 0; r < rows.length; r++) tableRows.push(rows[r]);
    }

    out.text = textParts.join('\n\n').trim();
    out.tables = tableRows;
    if (!out.text && !out.tables.length) warn('xlsx-empty', 'Excel 表格中没有可识别的文字。');
    return out;
  }

