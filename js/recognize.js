  function detectCurrencyGlobal(text) {
    var re = /(?:^|[^A-Za-z])(USD|EUR|CNY|RMB|GBP|JPY|AUD|CAD|HKD|SGD|CHF|AED)(?![A-Za-z])/gi;
    var counts = {};
    var order = [];
    var m;
    while ((m = re.exec(text))) {
      var code = m[1].toUpperCase() === 'RMB' ? 'CNY' : m[1].toUpperCase();
      if (!counts[code]) { counts[code] = 0; order.push(code); }
      counts[code]++;
    }
    var best = null;
    var bestCount = 0;
    order.forEach(function (code) {
      if (counts[code] > bestCount) { best = code; bestCount = counts[code]; }
    });
    return best;
  }

  function isNonOrderDateLabelLine(line) {
    var t = asString(line).trim();
    if (!t) return false;
    for (var i = 0; i < FIELD_RULES.length; i++) {
      var field = FIELD_RULES[i].field;
      if (field !== 'etd' && field !== 'eta' && field !== 'lcDate') continue;
      if (FIELD_RULES[i]._colon.test(t)) return true;
    }
    return false;
  }

  function applyGlobalFallbacks(rec, text, lines) {
    var fields = rec.fields;
    if (!isMeaningful(fields.currency)) {
      var currency = detectCurrencyGlobal(text);
      if (currency) setField(rec, 'currency', currency, 0.6, '文本中的币种代码：' + currency);
    }
    if (!isMeaningful(fields.incoterm)) {
      var inc = normalizeIncoterm(text);
      if (inc) setField(rec, 'incoterm', inc, 0.6, '文本中的贸易术语：' + inc);
    }
    if (!isMeaningful(fields.date)) {
      var dateLine = '';
      var dateISO = null;
      for (var i = 0; i < lines.length; i++) {
        if (isNonOrderDateLabelLine(lines[i])) continue;
        var iso = normalizeDate(lines[i]);
        if (iso) { dateISO = iso; dateLine = lines[i]; break; }
      }
      if (dateISO) setField(rec, 'date', dateISO, 0.55, dateLine);
    }
    if (!isMeaningful(fields.orderNo)) {
      var orderMatch = /\b(SO|SC)[-_\s]?\d{2,4}[-_\s]\d{2,6}\b/i.exec(text);
      if (orderMatch) setField(rec, 'orderNo', orderMatch[0].replace(/\s+/g, ''), 0.5, orderMatch[0]);
    }
    if (!isMeaningful(fields.transportMode)) {
      if (/\b(?:air\s*waybill|awb|by\s+air|air\s*freight)\b/i.test(text)) {
        setField(rec, 'transportMode', 'AIR', 0.6, '文本提及空运');
      } else if (isMeaningful(fields.vessel) || isMeaningful(fields.blNo) || /(?:\bby\s+sea\b|ocean\s*freight|海运)/i.test(text)) {
        setField(rec, 'transportMode', 'SEA', 0.55, '文本提及海运/船名');
      }
    }
    if (!isMeaningful(fields.finalDestination) && isMeaningful(fields.portOfDischarge) && isMeaningful(fields.countryOfDestination)) {
      // 目的港 + 目的国 不直接推导最终目的地，避免误填
    }
  }

