  function decodeText(bytes) {
    if (typeof TextDecoder === 'function') {
      try {
        return new TextDecoder('utf-8', { fatal: false }).decode(bytes);
      } catch (e) { /* fall through */ }
    }
    var out = '';
    for (var i = 0; i < bytes.length; i++) out += String.fromCharCode(bytes[i]);
    return out;
  }

  function decodeZipName(bytes, flags) {
    try {
      var name = decodeText(bytes);
      if ((flags & 0x800) || name.indexOf('\uFFFD') === -1) return name;
      var out = '';
      for (var i = 0; i < bytes.length; i++) out += String.fromCharCode(bytes[i]);
      return out;
    } catch (e) {
      return '';
    }
  }

  function readU16(bytes, offset) {
    return bytes[offset] | (bytes[offset + 1] << 8);
  }

  function readU32(bytes, offset) {
    return (bytes[offset] | (bytes[offset + 1] << 8) | (bytes[offset + 2] << 16) | (bytes[offset + 3] << 24)) >>> 0;
  }

  function readZipDirectory(bytes) {
    var out = { entries: [], warnings: [] };
    function warn(code, message) { out.warnings.push({ code: code, message: message }); }
    if (!bytes || bytes.length < 22) {
      warn('zip-invalid', 'ZIP 文件结构无效（文件过小），无法读取文档内容。');
      return out;
    }
    var eocd = -1;
    var min = Math.max(0, bytes.length - 22 - 65535);
    for (var i = bytes.length - 22; i >= min; i--) {
      if (readU32(bytes, i) === 0x06054b50) { eocd = i; break; }
    }
    if (eocd < 0) {
      warn('zip-invalid', '未找到 ZIP 目录（文件可能已损坏或不是有效的 Office 文档）。');
      return out;
    }
    var total = readU16(bytes, eocd + 10);
    var cdOffset = readU32(bytes, eocd + 16);
    if (total === 0xffff || cdOffset === 0xffffffff) {
      warn('zip64-unsupported', '文件使用 ZIP64 格式，当前版本暂不支持解析。');
      return out;
    }
    var p = cdOffset;
    var count = 0;
    while (p + 46 <= bytes.length && count < total) {
      if (readU32(bytes, p) !== 0x02014b50) {
        warn('zip-invalid', 'ZIP 中央目录损坏，仅能读取部分内容。');
        break;
      }
      var flags = readU16(bytes, p + 8);
      var method = readU16(bytes, p + 10);
      var compSize = readU32(bytes, p + 20);
      var uncompSize = readU32(bytes, p + 24);
      var nameLen = readU16(bytes, p + 28);
      var extraLen = readU16(bytes, p + 30);
      var commentLen = readU16(bytes, p + 32);
      var localOffset = readU32(bytes, p + 42);
      if (p + 46 + nameLen > bytes.length) {
        warn('zip-invalid', 'ZIP 中央目录条目越界，文件可能已损坏。');
        break;
      }
      var name = decodeZipName(bytes.subarray(p + 46, p + 46 + nameLen), flags);
      if (name && name.charAt(name.length - 1) !== '/') {
        out.entries.push({
          name: name.replace(/\\/g, '/'),
          method: method,
          compSize: compSize,
          uncompSize: uncompSize,
          localOffset: localOffset,
          flags: flags
        });
      }
      p += 46 + nameLen + extraLen + commentLen;
      count++;
    }
    if (!out.entries.length && !out.warnings.length) {
      warn('zip-invalid', 'ZIP 中没有可读取的文件条目。');
    }
    return out;
  }

  function inflateRaw(bytes) {
    return new Promise(function (resolve, reject) {
      try {
        if (typeof DecompressionStream !== 'function') {
          reject(new Error('当前环境不支持解压（DecompressionStream 不可用）'));
          return;
        }
        if (typeof Blob !== 'function' || typeof Response !== 'function') {
          reject(new Error('当前环境不支持解压所需的 Blob/Response'));
          return;
        }
        var stream = new Blob([bytes]).stream().pipeThrough(new DecompressionStream('deflate-raw'));
        new Response(stream).arrayBuffer().then(function (ab) {
          resolve(new Uint8Array(ab));
        }).catch(reject);
      } catch (e) {
        reject(e);
      }
    });
  }

  async function readZipEntry(bytes, entry) {
    if (!entry) throw new Error('条目不存在');
    if (entry.flags & 0x0001) throw new Error('文件已加密，无法读取');
    if (entry.uncompSize > 64 * 1024 * 1024) throw new Error('单个文件解压后过大');
    var offset = entry.localOffset;
    if (offset + 30 > bytes.length) throw new Error('本地文件头越界');
    if (readU32(bytes, offset) !== 0x04034b50) throw new Error('本地文件头无效');
    var nameLen = readU16(bytes, offset + 26);
    var extraLen = readU16(bytes, offset + 28);
    var start = offset + 30 + nameLen + extraLen;
    var end = start + entry.compSize;
    if (end > bytes.length) throw new Error('压缩数据越界');
    var data = bytes.subarray(start, end);
    if (entry.method === 0) return data;
    if (entry.method === 8) {
      var inflated = await inflateRaw(data);
      if (inflated.length > 64 * 1024 * 1024) throw new Error('解压后内容过大');
      return inflated;
    }
    throw new Error('不支持的压缩方式：' + entry.method);
  }

  function findZipEntry(entries, wantedPath) {
    var normalized = asString(wantedPath).replace(/\\/g, '/').replace(/^\//, '').toLowerCase();
    for (var i = 0; i < entries.length; i++) {
      var name = entries[i].name.replace(/^\//, '').toLowerCase();
      if (name === normalized) return entries[i];
    }
    return null;
  }

