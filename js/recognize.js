  function postProcessFields(rec) {
    var fields = rec.fields;
    // inline voyage inside vessel value (single-space docs)
    if (isMeaningful(fields.vessel) && !isMeaningful(fields.voyage)) {
      var m = /\s+(?:voyage|voy\.?|航次)\s*[:：]?\s*([A-Za-z0-9./\-]{1,16})\s*$/i.exec(fields.vessel);
      if (m) {
        var voyage = m[1].toUpperCase();
        var vessel = fields.vessel.slice(0, m.index).trim();
        if (vessel) {
          setField(rec, 'vessel', vessel, rec.meta['vessel'] ? rec.meta['vessel'].confidence : 0.9, rec.meta['vessel'] ? rec.meta['vessel'].evidence : vessel);
          setField(rec, 'voyage', voyage, 0.8, m[0]);
        }
      }
    }
    // inline "port of discharge" inside port of loading
    if (isMeaningful(fields.portOfLoading)) {
      var pd = /\s+port\s*of\s*(?:discharge|destination)\s*[:：]?\s*(.+)$/i.exec(fields.portOfLoading);
      if (pd) {
        var pol = fields.portOfLoading.slice(0, pd.index).trim();
        if (pol) {
          setField(rec, 'portOfLoading', cleanPlace(pol), 0.85, pol);
          if (!isMeaningful(fields.portOfDischarge)) setField(rec, 'portOfDischarge', cleanPlace(pd[1]), 0.8, pd[0]);
        }
      }
    }
  }

