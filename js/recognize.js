  function isBlankValue(value) {
    if (value === undefined || value === null) return true;
    if (typeof value === 'string') return value.trim() === '';
    if (typeof value === 'number') return value === 0 || !Number.isFinite(value);
    return false;
  }

  function sanitizeScalar(targetField, raw) {
    var s = asString(raw).trim();
    if (!s) return null;
    switch (targetField) {
      case 'date':
      case 'lcDate':
      case 'etd':
      case 'eta':
        return normalizeDate(s);
      case 'currency':
        return normalizeCurrency(s);
      case 'incoterm':
        return normalizeIncoterm(s);
      case 'transportMode':
        return normalizeTransportMode(s);
      case 'no':
      case 'lcNo':
      case 'vessel':
      case 'voyage':
      case 'containerNo':
      case 'sealNo':
      case 'blNo':
      case 'bookingNo':
      case 'portOfLoading':
      case 'portOfDischarge':
      case 'finalDestination':
      case 'countryOfDestination':
        return s;
      default:
        return asString(raw).replace(/\r\n?/g, '\n').trim();
    }
  }

  function sanitizeApplyItem(raw, core) {
    if (!raw || typeof raw !== 'object') return null;
    var nameEn = asString(raw.nameEn).trim();
    var nameCn = asString(raw.nameCn).trim();
    if (!nameEn && !nameCn) return null;
    function numOr(value, fallback) {
      var n = Number(value);
      if (!Number.isFinite(n) || n < 0) return fallback;
      return n;
    }
    var unit = normalizeUnit(raw.unit) || 'PCS';
    var origin = asString(raw.origin).trim() || 'CHINA';
    return {
      id: core.uid('item'),
      productId: '',
      code: asString(raw.code).trim(),
      nameEn: nameEn,
      nameCn: nameCn,
      hsCode: normalizeHsCode(raw.hsCode) || '',
      origin: origin,
      unit: unit,
      qty: core.round(numOr(raw.qty, 0), 3),
      unitPrice: core.round(numOr(raw.unitPrice, 0), 4),
      cartons: core.round(numOr(raw.cartons, 0), 3),
      qtyPerCarton: core.round(numOr(raw.qtyPerCarton, 0), 3),
      netWeight: core.round(numOr(raw.netWeight, 0), 3),
      grossWeight: core.round(numOr(raw.grossWeight, 0), 3),
      cbm: core.round(numOr(raw.cbm, 0), 3),
      costPrice: 0,
      remarks: ''
    };
  }

