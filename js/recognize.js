  function wordParagraphText(paragraphXml) {
    var parts = [];
    var re = /<w:t\b[^>]*>([\s\S]*?)<\/w:t>|<w:t\b[^>]*\/>|<w:tab\b[^>]*\/?>|<w:(?:br|cr)\b[^>]*\/?>/g;
    var m;
    while ((m = re.exec(paragraphXml))) {
      if (m[1] !== undefined) parts.push(decodeEntities(m[1]));
      else if (/^<w:tab/.test(m[0])) parts.push('\t');
      else if (/^<w:t\b/.test(m[0])) parts.push('');
      else parts.push('\n');
    }
    return parts.join('').replace(/[ \t]+$/g, '');
  }

  function wordTableRows(tableXml) {
    var rows = [];
    var trRe = /<w:tr\b[^>]*>/g;
    var trMatch;
    while ((trMatch = trRe.exec(tableXml))) {
      if (/\/>$/.test(trMatch[0])) continue;
      var trEnd = findMatchingClose(tableXml, trMatch.index, 'w:tr');
      if (trEnd < 0) break;
      var rowXml = tableXml.slice(trMatch.index, trEnd);
      var cells = [];
      var tcRe = /<w:tc\b[^>]*>/g;
      var tcMatch;
      while ((tcMatch = tcRe.exec(rowXml))) {
        if (/\/>$/.test(tcMatch[0])) continue;
        var tcEnd = findMatchingClose(rowXml, tcMatch.index, 'w:tc');
        if (tcEnd < 0) break;
        var cellXml = rowXml.slice(tcMatch.index, tcEnd);
        var paragraphs = [];
        var pRe = /<w:p\b[^>]*>/g;
        var pMatch;
        while ((pMatch = pRe.exec(cellXml))) {
          if (/\/>$/.test(pMatch[0])) { paragraphs.push(''); continue; }
          var pEnd = findMatchingClose(cellXml, pMatch.index, 'w:p');
          if (pEnd < 0) break;
          paragraphs.push(wordParagraphText(cellXml.slice(pMatch.index, pEnd)));
        }
        var cellText = paragraphs.map(function (t) { return t.replace(/[\t\n\r]+/g, ' '); }).join(' ');
        cells.push(collapseSpaces(cellText));
      }
      if (cells.length) rows.push(cells);
      trRe.lastIndex = trEnd;
    }
    return rows;
  }

  function parseWordXml(xml) {
    var out = { text: '', tables: [] };
    if (!xml) return out;
    var body = xml;
    var bodyMatch = /<w:body\b[^>]*>([\s\S]*)<\/w:body>/.exec(xml);
    if (bodyMatch) body = bodyMatch[1];
    var lines = [];
    var pos = 0;
    // Capture the complete start tag so self-closing `<w:p/>` / `<w:tbl/>`
    // can be detected without consuming the following block (empty paragraphs
    // between tables are common in real Word documents).
    var blockRe = /<(w:p|w:tbl)\b[^>]*>/g;
    while (pos < body.length) {
      blockRe.lastIndex = pos;
      var m = blockRe.exec(body);
      if (!m) break;
      if (m[1] === 'w:tbl') {
        if (/\/>$/.test(m[0])) { pos = m.index + m[0].length; continue; }
        var tblEnd = findMatchingClose(body, m.index, 'w:tbl');
        if (tblEnd < 0) break;
        var tblXml = body.slice(m.index, tblEnd);
        var rows = wordTableRows(tblXml);
        if (rows.length) {
          out.tables.push(rows);
          lines.push(rows.map(function (row) { return row.join('\t'); }).join('\n'));
        }
        pos = tblEnd;
      } else {
        if (/\/>$/.test(m[0])) { lines.push(''); pos = m.index + m[0].length; continue; }
        var pEnd = findMatchingClose(body, m.index, 'w:p');
        if (pEnd < 0) break;
        lines.push(wordParagraphText(body.slice(m.index, pEnd)));
        pos = pEnd;
      }
    }
    out.text = lines.join('\n').replace(/\n{3,}/g, '\n\n').replace(/[ \t]+\n/g, '\n').trim();
    return out;
  }

  async function extractDocxText(bytes) {
    var out = { text: '', tables: [], warnings: [] };
    function warn(code, message) { out.warnings.push({ code: code, message: message }); }
    if (!bytes || bytes.length < 22) {
      warn('docx-invalid', '无法读取 Word 文件：内容为空或已损坏。');
      return out;
    }
    var zip = readZipDirectory(bytes);
    out.warnings = out.warnings.concat(zip.warnings);
    if (!zip.entries.length) {
      if (!out.warnings.length) warn('docx-invalid', 'Word 文件结构无效，无法解析。');
      return out;
    }
    var entry = findZipEntry(zip.entries, 'word/document.xml');
    if (!entry) {
      warn('docx-invalid', '未找到 word/document.xml，文件可能不是有效的 .docx。');
      return out;
    }
    var xmlBytes;
    try {
      xmlBytes = await readZipEntry(bytes, entry);
    } catch (e) {
      warn('docx-invalid', '解压 Word 内容失败：' + (e && e.message ? e.message : '未知错误'));
      return out;
    }
    if (xmlBytes.length > 64 * 1024 * 1024) {
      warn('docx-too-large', 'Word 文档内容过大，已跳过解析。');
      return out;
    }
    var parsed = parseWordXml(decodeText(xmlBytes));
    out.text = parsed.text;
    out.tables = parsed.tables;
    if (!out.text && !out.tables.length) warn('docx-empty', 'Word 文档中没有可识别的文字。');
    return out;
  }

