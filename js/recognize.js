  function splitCells(line) {
    var s = asString(line);
    if (!s) return [''];
    var parts;
    if (s.indexOf('\t') >= 0) parts = s.split('\t');
    else if (/ {2,}/.test(s)) parts = s.split(/ {2,}/);
    else return [s.trim()];
    var cells = parts.map(function (part) { return part.trim(); });
    while (cells.length && cells[0] === '') cells.shift();
    while (cells.length && cells[cells.length - 1] === '') cells.pop();
    return cells;
  }

  function trimIdValue(rec, raw) {
    var value = collapseSpaces(raw);
    if (!value) return '';
    var dateTail = /\s+(?:date|dated|invoice\s*date|l\s*\/?\s*c\s*date)\s*[:：]\s*(.+)$/i.exec(value);
    if (dateTail) {
      var iso = normalizeDate(dateTail[1]);
      if (iso) {
        setField(rec, 'date', iso, 0.85, dateTail[1]);
        value = value.slice(0, dateTail.index).trim();
      }
    }
    if (!value) return '';
    return value;
  }

  function splitVesselVoyage(rec, raw, confidence, evidence) {
    var value = collapseSpaces(raw);
    if (!value) return '';
    var voyage = null;
    var vessel = value;
    var labeled = /\s+(?:voyage|voy\.?|航次)\s*[:：]?\s*([A-Za-z0-9./\-]{1,16})\s*$/i.exec(value);
    if (labeled) {
      voyage = collapseSpaces(labeled[1]);
      vessel = value.slice(0, labeled.index).trim();
    } else {
      var slash = /^(.*?)\s*[\/|]\s*([A-Za-z0-9.]{1,16})\s*$/.exec(value);
      if (slash && /^(?:V?\.?\d{1,5}[A-Z]?|\d{1,4}[EWNS])$/i.test(slash[2])) {
        vessel = slash[1].trim();
        voyage = slash[2];
      }
    }
    if (!vessel) return '';
    if (voyage && !isMeaningful(rec.fields.voyage)) {
      setField(rec, 'voyage', voyage.toUpperCase(), confidence * 0.95, evidence || raw);
    }
    return vessel;
  }

  function handleRuleValue(rec, rule, raw, line, confidence) {
    var valueRaw = asString(raw).replace(/[\u00a0\u3000]/g, ' ').trim();
    if (!valueRaw) return false;
    var field = rule.field;
    var conf = confidence === undefined ? rule.conf : confidence;
    var evidence = line || valueRaw;
    var value;
    switch (rule.type) {
      case 'date':
        var dateList = extractDateList(valueRaw);
        value = dateList.length ? dateList[0] : normalizeDate(valueRaw);
        if (!value) return false;
        var dateSet = setField(rec, field, value, conf, evidence);
        // 同一行 "ETD/ETA: 2026-12-10 / 2026-12-24"：第二个日期归 ETA
        if (field === 'etd' && dateList.length > 1 && !isMeaningful(rec.fields.eta)) {
          setField(rec, 'eta', dateList[1], conf * 0.9, evidence);
        }
        return dateSet;
      case 'currency':
        value = normalizeCurrency(valueRaw);
        if (!value) return false;
        return setField(rec, field, value, conf, evidence);
      case 'incoterm':
        value = normalizeIncoterm(valueRaw);
        if (!value) return false;
        return setField(rec, field, value, conf, evidence);
      case 'transport':
        value = normalizeTransportMode(valueRaw);
        if (!value) return false;
        return setField(rec, field, value, conf, evidence);
      case 'place':
        value = cleanPlace(valueRaw);
        if (!value) return false;
        return setField(rec, field, value, conf, evidence);
      case 'money':
        value = parseMoney(valueRaw);
        if (!(value > 0)) return false;
        return setField(rec, field, roundTo(value, 2), conf, evidence);
      case 'id':
        if (field === 'containerNo') {
          var containerMatch = /[A-Z]{4}\d{7}/i.exec(valueRaw);
          if (containerMatch) valueRaw = containerMatch[0];
        }
        value = trimIdValue(rec, valueRaw);
        if (!value) return false;
        return setField(rec, field, value, conf, evidence);
      case 'vessel':
        value = splitVesselVoyage(rec, valueRaw, conf, evidence);
        if (!value) return false;
        return setField(rec, field, value, conf, evidence);
      default:
        value = cleanValue(valueRaw);
        if (!value) return false;
        return setField(rec, field, value, conf, evidence);
    }
  }

  function splitCombinedSegments(valueText) {
    var s = asString(valueText).replace(/[:：]\s*$/, '').trim();
    if (!s) return [];
    var attempts = [
      /\s+\/\s+|\s*[／｜|]\s*|\s{2,}/,
      /\s*[\/／｜|]\s*|\s{2,}/
    ];
    for (var a = 0; a < attempts.length; a++) {
      var parts = s.split(attempts[a]).map(function (part) { return part.trim(); }).filter(Boolean);
      if (parts.length > 1) return parts;
    }
    return [s];
  }

  function parseCombinedLabelRules(labelText) {
    var text = asString(labelText).replace(/[:：]\s*$/, '').trim();
    if (!text) return null;
    if (!/[\/／|]|\s{2,}/.test(text)) return null;
    var segments = splitCombinedSegments(text);
    if (segments.length < 2 || segments.length > 4) return null;
    var rules = [];
    var seenFields = {};
    for (var i = 0; i < segments.length; i++) {
      var found = null;
      for (var r = 0; r < FIELD_RULES.length; r++) {
        if (FIELD_RULES[r]._exact.test(segments[i])) { found = FIELD_RULES[r]; break; }
      }
      if (!found) return null;
      // 同字段的中英合并标签（如 "Port of Loading / 起运港"）不做拆分，回退原有单标签逻辑
      if (seenFields[found.field]) return null;
      seenFields[found.field] = true;
      rules.push(found);
    }
    return rules;
  }

  // 支持合并标签行，如 "Port of Loading / Port of Discharge" => "SHANGHAI / SYDNEY"、
  // "Vessel / Voyage" => "OOCL BRISBANE / V.118E"、"ETD / ETA" => "2026-12-18 / 2027-01-05"。
  // 仅在标签可完整拆分为已知字段且值可等分时才生效，其余情况返回 false 走原有单标签逻辑。
  function tryApplyCombinedFields(rec, labelText, valueText, rawLine) {
    var rules = parseCombinedLabelRules(labelText);
    if (!rules) return false;
    var values = splitCombinedSegments(valueText);
    if (values.length !== rules.length) return false;
    var applied = false;
    for (var i = 0; i < rules.length; i++) {
      if (handleRuleValue(rec, rules[i], values[i], rawLine, 0.85)) applied = true;
    }
    return applied;
  }

  function tryCombinedColonLine(rec, line) {
    var m = /^([^:：]+)[:：]\s*(.*)$/.exec(asString(line));
    if (!m) return false;
    return tryApplyCombinedFields(rec, m[1], m[2], line);
  }

  function applyRulesToCell(rec, cell, rawLine, confidence) {
    if (!cell) return;
    if (tryCombinedColonLine(rec, cell)) return;
    for (var r = 0; r < FIELD_RULES.length; r++) {
      var rule = FIELD_RULES[r];
      var m = rule._colon.exec(cell);
      if (!m) continue;
      var val = (m[1] || '').trim();
      if (!val) continue;
      if (handleRuleValue(rec, rule, val, rawLine, confidence === undefined ? rule.conf : confidence)) return;
    }
  }

  function nextContinuationValue(lines, index) {
    for (var i = index + 1; i < lines.length && i <= index + 3; i++) {
      var line = asString(lines[i]).trim();
      if (!line) continue;
      if (mapHeaderCells(splitCells(line)).mapped >= 3) return '';
      var isLabel = false;
      for (var r = 0; r < FIELD_RULES.length; r++) {
        if (FIELD_RULES[r]._colon.test(line)) { isLabel = true; break; }
      }
      if (isLabel || line.length > 160) return '';
      return line;
    }
    return '';
  }

  function extractGenericFields(rec, lines) {
    for (var i = 0; i < lines.length; i++) {
      var line = lines[i];
      if (!line || !line.trim()) continue;
      var cells = splitCells(line);
      if (cells.length > 1) {
        for (var c = 0; c < cells.length; c++) {
          applyRulesToCell(rec, cells[c], line);
        }
        for (var p = 0; p < cells.length - 1; p++) {
          if (tryApplyCombinedFields(rec, cells[p], cells[p + 1], line)) continue;
          for (var r = 0; r < FIELD_RULES.length; r++) {
            var rule = FIELD_RULES[r];
            if (!rule._exact.test(cells[p])) continue;
            var val = cells[p + 1];
            if (!val) break;
            if (handleRuleValue(rec, rule, val, line, 0.85)) break;
          }
        }
      } else {
        if (tryCombinedColonLine(rec, line)) continue;
        for (var r2 = 0; r2 < FIELD_RULES.length; r2++) {
          var rule2 = FIELD_RULES[r2];
          var m = rule2._colon.exec(line);
          if (!m) continue;
          var value = (m[1] || '').trim();
          if (!value && rule2.continuation) value = nextContinuationValue(lines, i);
          if (!value) continue;
          if (handleRuleValue(rec, rule2, value, line, rule2.conf)) break;
        }
      }
    }
  }

