  function parse(text, options) {
    var opts = options && typeof options === 'object' ? options : {};
    var rec = emptyRecognition();
    try {
      var rawInput = asString(text);
      var inputChars = rawInput.length;
      var normalized = normalizeText(rawInput);
      var truncated = false;
      if (normalized.length > MAX_TEXT_CHARS) {
        normalized = normalized.slice(0, MAX_TEXT_CHARS);
        truncated = true;
      }
      var lines = normalized.split('\n');
      var tables = normalizeTables(opts.tables);
      var hasText = normalized.trim().length > 0;
      var hasTables = tables.some(function (row) { return Array.isArray(row) && row.length > 0; });

      rec.stats.chars = inputChars;
      if (hasText) {
        rec.texts = [{ name: 'text', chars: inputChars, excerpt: makeExcerpt(normalized) }];
      }
      if (truncated) {
        rec.warnings.push({ code: 'text-too-long', message: '文本超过 300,000 字符，已截断识别。' });
      }
      if (!hasText && !hasTables) {
        rec.warnings.push({ code: 'empty-text', message: '未提供可识别的内容，请粘贴文字或上传文档。' });
        rec.stats.fieldCount = 0;
        rec.stats.itemCount = 0;
        return rec;
      }

      if (hasText) {
        var sellerInfo = extractSeller(rec, lines);
        var buyerFound = extractBuyer(rec, lines);
        extractShippingMarks(rec, lines);
        extractRemarks(rec, lines);
        extractGenericFields(rec, lines);
        postProcessFields(rec);
        applyGlobalFallbacks(rec, normalized, lines);
        resolvePartyConflict(rec, sellerInfo);
        if (!buyerFound && rec.fields.buyer && rec.fields.buyer.nameEn) {
          // keep whatever generic rules may have produced (none); guard for future changes
        }
      }

      var itemResult = { items: [], metas: [], derived: false };
      if (hasTables) itemResult = scanItemTables(tables, false);
      if (!itemResult.items.length && hasText) {
        itemResult = scanPseudoTables(extractPseudoTables(lines));
      }
      if (!itemResult.items.length && hasText) {
        itemResult = parseItemLines(lines);
      }
      rec.items = itemResult.items;
      collectItemMeta(rec, itemResult.items.length ? [itemResult] : []);
      if (itemResult.derived) {
        rec.warnings.push({ code: 'items-derived', message: '部分货物数量/单价/金额由其它列推算得出，请核对。' });
      }
      if (hasText && !rec.items.length) {
        rec.warnings.push({ code: 'no-items', message: '未识别到货物明细，请手动添加或检查表格格式。' });
      }
      if (!hasText && hasTables && !rec.items.length) {
        rec.warnings.push({ code: 'no-items', message: '表格中未识别到货物明细。' });
      }
      rec.stats.fieldCount = countFieldCount(rec.fields);
      rec.stats.itemCount = rec.items.length;
    } catch (err) {
      rec.warnings.push({
        code: 'parse-error',
        message: '解析过程出现异常，已返回部分结果：' + (err && err.message ? err.message : '未知错误')
      });
    }
    return rec;
  }

  function resolvePartyConflict(rec, sellerInfo) {
    var seller = rec.fields.seller;
    var buyer = rec.fields.buyer;
    if (!seller || !buyer) return;
    var sellerName = seller.nameEn;
    if (!sellerName || !buyer.nameEn) return;
    if (normNameKey(sellerName) !== normNameKey(buyer.nameEn)) return;
    var sellerConfidence = rec.meta['seller.nameEn'] ? rec.meta['seller.nameEn'].confidence : 0;
    if (sellerInfo && sellerInfo.explicit) {
      clearBuyerFields(rec);
      rec.warnings.push({
        code: 'buyer-seller-conflict',
        message: '买方名称与卖方相同，已清空买方识别结果，请手动填写买方。'
      });
    } else {
      clearField(rec, 'seller.nameEn');
      clearField(rec, 'seller.addressEn');
      clearField(rec, 'seller.country');
      clearField(rec, 'seller.tel');
      clearField(rec, 'seller.email');
      clearField(rec, 'seller.taxId');
      if (sellerConfidence < 0.8) {
        rec.warnings.push({
          code: 'seller-uncertain',
          message: '自动识别的卖方名称与买方相同，已忽略卖方结果，请核对买卖双方。'
        });
      }
    }
  }

