  function decodeEntities(value) {
    return asString(value).replace(/&#x([0-9a-fA-F]+);/g, function (m, hex) {
      var code = parseInt(hex, 16);
      if (!Number.isFinite(code) || code < 0 || code > 0x10ffff) return m;
      try { return String.fromCodePoint(code); } catch (e) { return m; }
    }).replace(/&#(\d+);/g, function (m, dec) {
      var code = parseInt(dec, 10);
      if (!Number.isFinite(code) || code < 0 || code > 0x10ffff) return m;
      try { return String.fromCodePoint(code); } catch (e) { return m; }
    }).replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"')
      .replace(/&apos;/g, "'").replace(/&nbsp;/g, ' ').replace(/&amp;/g, '&');
  }

  function xmlAttr(attrs, name) {
    if (!attrs) return '';
    var escaped = asString(name).replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    var re = new RegExp('(?:^|\\s)' + escaped + '\\s*=\\s*"([^"]*)"');
    var m = re.exec(attrs);
    return m ? decodeEntities(m[1]) : '';
  }

  function findMatchingClose(source, start, tagName) {
    var re = new RegExp('<(\\/?)' + tagName + '\\b[^>]*>', 'g');
    re.lastIndex = start;
    var depth = 0;
    var m;
    while ((m = re.exec(source))) {
      if (m[1] === '/') {
        depth--;
        if (depth === 0) return m.index + m[0].length;
      } else if (!/\/>$/.test(m[0])) {
        depth++;
      }
    }
    return -1;
  }

