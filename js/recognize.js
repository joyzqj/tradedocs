  function isHardLabelLine(line) {
    var t = asString(line).trim();
    if (!t) return false;
    if (BUYER_BLOCK_STOP.test(t) || SELLER_BLOCK_STOP.test(t)) return true;
    for (var i = 0; i < FIELD_RULES.length; i++) {
      if (FIELD_RULES[i]._colon.test(t)) return true;
    }
    if (MARKS_COLON.test(t) || REMARKS_COLON.test(t)) return true;
    if (startsWithFieldLabel(t)) return true;
    if (mapHeaderCells(splitCells(t)).mapped >= 3) return true;
    if (/^(?:total|subtotal|sub-total|grand\s*total|合计|总计|小计)\b/i.test(t)) return true;
    return false;
  }

