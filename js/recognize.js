  function isBlockTerminator(line) {
    var t = collapseSpaces(line);
    if (!t) return true;
    if (/^(?:total|subtotal|sub-total|grand\s*total|items?|goods|description|remarks?|notes?|payment|freight|insurance|discount|bank|beneficiary|account|swift|tel|fax|email|date|page|signed|authorized|etd|eta)\b/i.test(t)) return true;
    if (/^(?:e\.?t\.?[da]\.?|estimated\s+(?:time|departure|arrival|sailing))\b/i.test(t)) return true;
    if (/^(?:合计|总计|小计|货物|品名|付款|运费|保险|银行|备注|说明|日期|页码)/.test(t)) return true;
    if (/^(?:buyer|seller|supplier|exporter|shipper|consignee|notify|to|bill\s*to|sold\s*to|attn|contact|address|country|port\s*of|final\s*destination|vessel|voyage|order\s*no|invoice\s*no|contract\s*no|currency|incoterm|transport|container|seal|b\s*\/?\s*l\s*no|booking|l\s*\/?\s*c|date)\s*[:：\t]/i.test(t)) return true;
    if (mapHeaderCells(splitCells(line)).mapped >= 3) return true;
    return false;
  }

  function captureBlockAfter(lines, index, maxLines) {
    var values = [];
    var limit = Math.min(lines.length, index + 1 + maxLines);
    for (var k = index + 1; k < limit; k++) {
      var line = asString(lines[k]);
      if (!line.trim()) break;
      if (isBlockTerminator(line)) break;
      values.push(line.trim());
    }
    return values;
  }

