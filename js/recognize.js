  function isMeaningful(value) {
    if (value === null || value === undefined) return false;
    if (typeof value === 'string') return value.trim().length > 0;
    if (typeof value === 'number') return Number.isFinite(value);
    return true;
  }

  function setField(rec, path, value, confidence, evidence) {
    if (!isMeaningful(value)) return false;
    var parts = asString(path).split('.');
    var target = rec.fields;
    for (var i = 0; i < parts.length - 1; i++) {
      if (!target || typeof target !== 'object') return false;
      target = target[parts[i]];
    }
    if (!target || typeof target !== 'object') return false;
    var key = parts[parts.length - 1];
    var previousMeta = rec.meta[path];
    if (previousMeta && previousMeta.confidence > confidence && isMeaningful(target[key])) return false;
    target[key] = value;
    rec.meta[path] = { confidence: clampConfidence(confidence), evidence: makeEvidence(evidence || value) };
    return true;
  }

