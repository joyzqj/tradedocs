  function rowsToItems(header, rows, baseIndex) {
    var result = { items: [], metas: [], derived: false };
    var keys = {};
    Object.keys(header.keys).forEach(function (k) { keys[k] = header.keys[k]; });
    if (keys.code !== undefined) {
      var codeValues = [];
      rows.forEach(function (cells) {
        var v = headerKeyValue(cells, keys, 'code');
        if (v) codeValues.push(v);
      });
      var numericIncreasing = codeValues.length >= 2;
      if (numericIncreasing) {
        for (var c = 0; c < codeValues.length; c++) {
          if (!/^\d{1,3}$/.test(codeValues[c])) { numericIncreasing = false; break; }
          if (c > 0 && parseInt(codeValues[c], 10) !== parseInt(codeValues[c - 1], 10) + 1) { numericIncreasing = false; break; }
        }
      }
      if (numericIncreasing) delete keys.code;
    }
    rows.forEach(function (cells) {
      var rowText = cells.map(function (cell) { return asString(cell); }).filter(function (cell) { return cell !== ''; }).join(' | ');
      var nameRaw = headerKeyValue(cells, keys, 'nameEn');
      var codeRaw = headerKeyValue(cells, keys, 'code');
      if (!nameRaw && codeRaw) { nameRaw = codeRaw; codeRaw = ''; }
      if (!nameRaw) return;
      var hsRaw = headerKeyValue(cells, keys, 'hsCode');
      var qtyRaw = headerKeyValue(cells, keys, 'qty');
      var unitRaw = headerKeyValue(cells, keys, 'unit');
      var qty = parseNumberCell(qtyRaw);
      var unitPrice = parseMoney(headerKeyValue(cells, keys, 'unitPrice'));
      var amount = parseMoney(headerKeyValue(cells, keys, 'amount'));
      var cartons = parseNumberCell(headerKeyValue(cells, keys, 'cartons'));
      var qtyPerCarton = parseNumberCell(headerKeyValue(cells, keys, 'qtyPerCarton'));
      var netWeight = parseNumberCell(headerKeyValue(cells, keys, 'netWeight'));
      var grossWeight = parseNumberCell(headerKeyValue(cells, keys, 'grossWeight'));
      var cbm = parseNumberCell(headerKeyValue(cells, keys, 'cbm'));
      var unit = normalizeUnit(unitRaw) || extractUnitToken(qtyRaw);

      if (qty !== null && qty <= 0) qty = null;
      if (unitPrice !== null && unitPrice <= 0) unitPrice = null;
      if (amount !== null && amount <= 0) amount = null;
      if (cartons !== null && cartons <= 0) cartons = null;
      if (qtyPerCarton !== null && qtyPerCarton <= 0) qtyPerCarton = null;
      if (netWeight !== null && netWeight <= 0) netWeight = null;
      if (grossWeight !== null && grossWeight <= 0) grossWeight = null;
      if (cbm !== null && cbm <= 0) cbm = null;

      var derivedFields = [];
      if (unitPrice === null && amount !== null && qty !== null && qty > 0) {
        unitPrice = roundTo(amount / qty, 4);
        derivedFields.push('unitPrice');
      }
      if (amount === null && unitPrice !== null && qty !== null && qty > 0) {
        amount = roundTo(qty * unitPrice, 2);
        derivedFields.push('amount');
      }
      if (qty === null && unitPrice !== null && amount !== null && unitPrice > 0) {
        var derivedQty = amount / unitPrice;
        if (Number.isFinite(derivedQty) && derivedQty > 0 && Math.abs(derivedQty - Math.round(derivedQty)) < 0.001) {
          qty = Math.round(derivedQty);
          derivedFields.push('qty');
        }
      }
      if (qty === null && unitPrice === null && amount === null) return;
      if (qty === null && amount === null && unitPrice === null) return;

      var nameParts = splitBilingualName(nameRaw);
      var item = {
        nameEn: nameParts.nameEn,
        nameCn: nameParts.nameCn,
        code: codeRaw || null,
        hsCode: normalizeHsCode(hsRaw),
        qty: qty,
        unit: unit,
        unitPrice: unitPrice,
        amount: amount,
        cartons: cartons,
        qtyPerCarton: qtyPerCarton,
        netWeight: netWeight,
        grossWeight: grossWeight,
        cbm: cbm
      };
      if (derivedFields.length) result.derived = true;
      var metaMap = {};
      var confidence = derivedFields.length ? 0.5 : 0.85;
      ITEM_FIELD_KEYS.forEach(function (key) {
        var val = item[key];
        if (!isMeaningful(val)) return;
        metaMap['items.' + (baseIndex + result.items.length) + '.' + key] = {
          confidence: derivedFields.indexOf(key) >= 0 ? 0.5 : confidence,
          evidence: makeEvidence(rowText || nameRaw)
        };
      });
      result.items.push(item);
      result.metas.push(metaMap);
    });
    return result;
  }

  function scanItemTables(tables, strict) {
    var result = { items: [], metas: [], derived: false };
    if (!Array.isArray(tables) || !tables.length) return result;
    var i = 0;
    while (i < tables.length) {
      var row = tables[i];
      if (!Array.isArray(row) || row.length < 2) { i++; continue; }
      var header = mapHeaderCells(row);
      if (!isItemHeader(header)) { i++; continue; }
      var headerLen = row.length;
      var dataRows = [];
      var j = i + 1;
      while (j < tables.length) {
        var nextRow = tables[j];
        if (!Array.isArray(nextRow) || nextRow.length === 0) break;
        if (nextRow.length < 2) break;
        var nextHeader = mapHeaderCells(nextRow);
        if (isItemHeader(nextHeader)) break;
        if (isTotalRow(nextRow)) break;
        if (strict) {
          if (nextRow.length !== headerLen) break;
        } else if (nextRow.length > headerLen + 2) {
          break;
        }
        dataRows.push(nextRow);
        j++;
      }
      if (dataRows.length) {
        var block = rowsToItems(header, dataRows, result.items.length);
        for (var k = 0; k < block.items.length; k++) {
          result.items.push(block.items[k]);
          result.metas.push(block.metas[k]);
        }
        if (block.derived) result.derived = true;
      }
      i = j;
    }
    return result;
  }

  var UNIT_TOKEN_SOURCE = 'PCS?|PIECES?|SETS?|CTNS?|CARTONS?|CASES?|BOXES?|PAIRS?|PACKS?|ROLLS?|DOZ(?:ENS?)?|KGS?|MTS?|TONS?|UNITS?|BAGS?|PALLETS?|个|件|套|只|箱|千克|公斤|台|米|卷|打|双';

  function stripSpans(text, spans) {
    var chars = asString(text).split('');
    spans.forEach(function (span) {
      for (var i = span.start; i < span.end && i < chars.length; i++) chars[i] = ' ';
    });
    return chars.join('');
  }

  function stripValidDateSpans(text) {
    var work = asString(text);
    var spans = [];
    var re = new RegExp(DATE_TEXT_RE.source, 'gi');
    var m;
    while ((m = re.exec(work))) {
      if (m[0] && normalizeDate(m[0])) spans.push({ start: m.index, end: m.index + m[0].length });
    }
    return stripSpans(work, spans);
  }

  function parseItemLine(line) {
    var original = asString(line).trim();
    if (!original || original.length < 5) return null;
    var work = original.replace(/^\s*\d{1,3}\s*[.)、]\s+/, ' ');
    // remove valid dates first so date digits never become money/quantity/HS
    work = stripValidDateSpans(work);
    var hsCode = null;
    var hsMatch = /\b(\d{4}(?:[.\-]\d{2}){1,4}|\d{6,10})\b/.exec(work);
    if (hsMatch) {
      hsCode = normalizeHsCode(hsMatch[1]);
      if (hsCode) work = work.slice(0, hsMatch.index) + ' ' + work.slice(hsMatch.index + hsMatch[0].length);
    }
    var spanList = [];
    var qty = null;
    var unit = null;
    var qtyRe = new RegExp('(\\d[\\d,]*(?:\\.\\d+)?)\\s*(' + UNIT_TOKEN_SOURCE + ')\\b', 'i');
    var qtyMatch = qtyRe.exec(work);
    if (qtyMatch) {
      qty = toNumber(qtyMatch[1]);
      unit = normalizeUnit(qtyMatch[2]);
      spanList.push({ start: qtyMatch.index, end: qtyMatch.index + qtyMatch[0].length });
    }
    // 先剔除数量/日期/HS 片段（等长替换），避免数量被误判为金额
    var moneyWork = stripSpans(work, spanList);
    var moneySpans = [];
    var currencyRe = /(?:USD|EUR|CNY|RMB|GBP|JPY|AUD|CAD|HKD|SGD|CHF|AED|US\$|\$|€|£|¥)\s*(\d[\d,]*(?:\.\d+)?)/gi;
    var currencyMatch;
    while ((currencyMatch = currencyRe.exec(moneyWork))) {
      moneySpans.push({
        start: currencyMatch.index,
        end: currencyMatch.index + currencyMatch[0].length,
        value: toNumber(currencyMatch[1])
      });
    }
    var decimalRe = /(?:^|[\s(])(\d{1,3}(?:,\d{3})+(?:\.\d{2,4})?|\d+\.\d{2,4})(?=$|[\s),;])/g;
    var decimalMatch;
    while ((decimalMatch = decimalRe.exec(moneyWork))) {
      var start = decimalMatch.index + decimalMatch[0].indexOf(decimalMatch[1]);
      moneySpans.push({ start: start, end: start + decimalMatch[1].length, value: toNumber(decimalMatch[1]) });
    }
    moneySpans.sort(function (a, b) { return a.start - b.start; });
    var mergedSpans = [];
    moneySpans.forEach(function (span) {
      if (span.value === null || !(span.value > 0)) return;
      for (var m = 0; m < mergedSpans.length; m++) {
        if (span.start < mergedSpans[m].end && span.end > mergedSpans[m].start) {
          if ((span.end - span.start) > (mergedSpans[m].end - mergedSpans[m].start)) mergedSpans[m] = span;
          return;
        }
      }
      mergedSpans.push(span);
    });
    var values = mergedSpans.map(function (span) { return span.value; });
    var unitPrice = null;
    var amount = null;
    var derived = false;
    if (values.length >= 2) {
      var first = values[0];
      var last = values[values.length - 1];
      if (qty !== null && qty > 0 && Math.abs(first * qty - last) <= Math.max(0.02, last * 0.02)) {
        unitPrice = first;
        amount = last;
      } else if (qty !== null && qty > 0 && Math.abs(last * qty - first) <= Math.max(0.02, first * 0.02)) {
        unitPrice = last;
        amount = first;
      } else {
        unitPrice = first;
        amount = last;
        derived = true;
      }
    } else if (values.length === 1) {
      var single = values[0];
      if (qty !== null && qty > 0) {
        if (single < 1 || single < qty / 10) {
          unitPrice = single;
          amount = roundTo(qty * single, 2);
        } else if (single > qty) {
          amount = single;
          unitPrice = roundTo(single / qty, 4);
        } else {
          unitPrice = single;
          amount = roundTo(qty * single, 2);
        }
        derived = true;
      } else {
        unitPrice = single;
      }
    }
    if (qty === null && unitPrice === null && amount === null) return null;
    if (qty !== null && qty <= 0) qty = null;
    if (unitPrice !== null && unitPrice <= 0) unitPrice = null;
    if (amount !== null && amount <= 0) amount = null;
    if (qty === null && unitPrice === null && amount === null) return null;

    var description = stripSpans(work, spanList.concat(mergedSpans));
    description = description.replace(/\b(?:USD|EUR|CNY|RMB|GBP|JPY|AUD|CAD|HKD|SGD|CHF|AED)\b/gi, ' ');
    description = description.replace(/[%％]/g, ' ');
    description = collapseSpaces(description);
    description = description.replace(/^[\s,;:：\-–—\/|()（）\[\]]+|[\s,;:：\-–—\/|()（）\[\]]+$/g, '').trim();
    description = description.replace(/^(?:HS|H\.S\.|HS CODE)\b\s*[:：]?\s*/i, '').trim();
    if (description.length < 2) return null;
    if (!/[A-Za-z\u3400-\u9fff]/.test(description)) return null;
    if (description.length > 120) description = description.slice(0, 120);

    var nameParts = splitBilingualName(description);
    if (!nameParts.nameEn && !nameParts.nameCn) return null;
    var item = {
      nameEn: nameParts.nameEn,
      nameCn: nameParts.nameCn,
      code: null,
      hsCode: hsCode,
      qty: qty,
      unit: unit,
      unitPrice: unitPrice,
      amount: amount,
      cartons: null,
      qtyPerCarton: null,
      netWeight: null,
      grossWeight: null,
      cbm: null
    };
    var metaMap = {};
    ITEM_FIELD_KEYS.forEach(function (key) {
      var val = item[key];
      if (!isMeaningful(val)) return;
      metaMap['items.__INDEX__.' + key] = {
        confidence: derived && (key === 'unitPrice' || key === 'amount' || key === 'qty') ? 0.45 : 0.6,
        evidence: makeEvidence(original)
      };
    });
    return { item: item, meta: metaMap, derived: derived };
  }

  function extractPseudoTables(lines) {
    var blocks = [];
    for (var i = 0; i < lines.length; i++) {
      var cells = splitCells(lines[i]);
      if (cells.length < 3) continue;
      var header = mapHeaderCells(cells);
      if (!isItemHeader(header)) continue;
      var rows = [];
      var j = i + 1;
      while (j < lines.length && rows.length < 200) {
        var line = asString(lines[j]);
        if (!line.trim()) break;
        var rowCells = splitCells(line);
        if (rowCells.length < 2) break;
        if (isItemHeader(mapHeaderCells(rowCells))) break;
        if (isTotalRow(rowCells)) break;
        if (rowCells.length !== cells.length) break;
        rows.push(rowCells);
        j++;
      }
      if (rows.length) blocks.push({ headerRow: cells, rows: rows });
      i = j;
    }
    return blocks;
  }

  function scanPseudoTables(blocks) {
    var result = { items: [], metas: [], derived: false };
    blocks.forEach(function (block) {
      var header = mapHeaderCells(block.headerRow);
      if (!isItemHeader(header)) return;
      var mapped = rowsToItems(header, block.rows, result.items.length);
      for (var k = 0; k < mapped.items.length; k++) {
        result.items.push(mapped.items[k]);
        result.metas.push(mapped.metas[k]);
      }
      if (mapped.derived) result.derived = true;
    });
    return result;
  }

  function parseItemLines(lines) {
    var result = { items: [], metas: [], derived: false };
    var count = 0;
    var skipPrefix = /^(?:freight|insurance|discount|sub-?total|total|amount|tax|vat|deposit|balance|page|signed|authorized|bank|beneficiary|account|swift|tel|fax|email|remark|note|signature|prepared|checked)\b/i;
    for (var i = 0; i < lines.length && count < 100; i++) {
      var line = asString(lines[i]).trim();
      if (!line || line.length < 6 || line.length > 500) continue;
      if (isTotalRow([line])) continue;
      if (skipPrefix.test(line)) continue;
      if (isHardLabelLine(line)) continue;
      var parsed = parseItemLine(line);
      if (!parsed) continue;
      var index = result.items.length;
      var metaMap = {};
      Object.keys(parsed.meta).forEach(function (key) {
        metaMap[key.replace('__INDEX__', String(index))] = parsed.meta[key];
      });
      result.items.push(parsed.item);
      result.metas.push(metaMap);
      if (parsed.derived) result.derived = true;
      count++;
    }
    return result;
  }

