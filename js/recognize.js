  function extOf(name) {
    var m = /\.([A-Za-z0-9]+)\s*$/.exec(asString(name));
    return m ? '.' + m[1].toLowerCase() : '';
  }

  function unsupportedWarning(ext) {
    var message;
    if (ext === '.pdf') {
      message = '当前版本不支持 PDF（含扫描件）。请将文字内容复制粘贴，或另存为 TXT/Word/Excel 后重试。';
    } else if (IMAGE_EXTS.indexOf(ext) >= 0) {
      message = '当前版本不支持图片识别。请粘贴文字，或上传 TXT/Word/Excel 文件。';
    } else if (ext === '.doc' || ext === '.xls') {
      message = '当前版本不支持旧版 Office 格式（.doc/.xls）。请另存为 .docx/.xlsx，或粘贴文字。';
    } else {
      message = '不支持的文件类型' + (ext ? '（' + ext + '）' : '') + '。当前仅支持 TXT/MD/CSV/TSV/JSON/DOCX/XLSX。';
    }
    return { code: 'unsupported-format', message: message };
  }

  async function readFileText(file) {
    if (file && typeof file.text === 'function') {
      var text = await file.text();
      return asString(text);
    }
    var bytes = await readFileBytes(file);
    return decodeText(bytes);
  }

  async function readFileBytes(file) {
    if (file && typeof file.arrayBuffer === 'function') {
      var ab = await file.arrayBuffer();
      return new Uint8Array(ab);
    }
    if (file && typeof file.stream === 'function' && typeof Response === 'function') {
      var ab2 = await new Response(file.stream()).arrayBuffer();
      return new Uint8Array(ab2);
    }
    if (typeof file === 'string') return new TextEncoder().encode(file);
    throw new Error('无法读取文件内容');
  }

  function flattenTableList(tables) {
    var flat = [];
    (Array.isArray(tables) ? tables : []).forEach(function (table) {
      if (!Array.isArray(table)) return;
      var isNested = false;
      for (var i = 0; i < table.length; i++) {
        if (Array.isArray(table[i])) { isNested = true; break; }
      }
      if (isNested) {
        for (var j = 0; j < table.length; j++) {
          if (Array.isArray(table[j])) flat.push(table[j]);
        }
        flat.push([]);
      } else {
        flat.push(table);
      }
    });
    while (flat.length && Array.isArray(flat[flat.length - 1]) && flat[flat.length - 1].length === 0) flat.pop();
    return flat;
  }

  async function extractFile(file) {
    var name = 'file';
    var size = 0;
    var warnings = [];
    try {
      if (file && typeof file.name === 'string' && file.name) name = file.name;
    } catch (e) { /* ignore */ }
    try {
      if (file && typeof file.size === 'number' && Number.isFinite(file.size)) size = file.size;
    } catch (e2) { /* ignore */ }
    var ext = extOf(name);
    var result = { name: name, ext: ext, size: size, text: '', tables: [], warnings: warnings };

    if (file === null || file === undefined) {
      warnings.push({ code: 'read-failed', message: '文件对象为空，无法读取。' });
      return result;
    }
    if (!ext || ACCEPT.indexOf(ext) < 0) {
      warnings.push(unsupportedWarning(ext));
      return result;
    }
    if (size > MAX_FILE_BYTES) {
      warnings.push({
        code: 'file-too-large',
        message: '文件超过 10 MB 限制（' + Math.round(size / 1024) + ' KB），已跳过。'
      });
      return result;
    }

    try {
      if (ext === '.txt' || ext === '.md') {
        var text = normalizeText(await readFileText(file));
        if (ext === '.md') result.tables = flattenTableList(markdownTables(text));
        result.text = text;
      } else if (ext === '.csv' || ext === '.tsv') {
        var raw = normalizeText(await readFileText(file));
        var delimiter = sniffDelimiter(raw, ext);
        var rows = parseDelimitedText(raw, delimiter);
        result.tables = rows;
        result.text = rows.map(function (row) { return row.join('\t'); }).join('\n');
      } else if (ext === '.json') {
        var rawJson = normalizeText(await readFileText(file));
        var parsed;
        try {
          parsed = JSON.parse(rawJson);
        } catch (e3) {
          warnings.push({ code: 'json-invalid', message: 'JSON 解析失败，已按纯文本处理。' });
          result.text = rawJson;
          return result;
        }
        var jsonResult = extractJsonText(parsed);
        result.text = jsonResult.text;
        result.tables = flattenTableList(jsonResult.tables);
        if (!result.text && !result.tables.length) {
          warnings.push({ code: 'empty-file', message: 'JSON 中没有可识别的数据。' });
        }
      } else if (ext === '.docx') {
        var docxBytes = await readFileBytes(file);
        if (!size) result.size = docxBytes.length;
        if (docxBytes.length > MAX_FILE_BYTES) {
          warnings.push({ code: 'file-too-large', message: '文件超过 10 MB 限制，已跳过。' });
          return result;
        }
        var docxResult = await extractDocxText(docxBytes);
        result.text = docxResult.text;
        result.tables = docxResult.tables;
        result.warnings = result.warnings.concat(docxResult.warnings);
      } else if (ext === '.xlsx') {
        var xlsxBytes = await readFileBytes(file);
        if (!size) result.size = xlsxBytes.length;
        if (xlsxBytes.length > MAX_FILE_BYTES) {
          warnings.push({ code: 'file-too-large', message: '文件超过 10 MB 限制，已跳过。' });
          return result;
        }
        var xlsxResult = await extractXlsxText(xlsxBytes);
        result.text = xlsxResult.text;
        result.tables = xlsxResult.tables;
        result.warnings = result.warnings.concat(xlsxResult.warnings);
      }
    } catch (err) {
      warnings.push({
        code: 'read-failed',
        message: '读取文件失败：' + (err && err.message ? err.message : '未知错误')
      });
    }

    if (result.text.length > MAX_TEXT_CHARS) {
      result.text = result.text.slice(0, MAX_TEXT_CHARS);
      warnings.push({ code: 'text-truncated', message: '文件文本超过 300,000 字符，已截断。' });
    }
    if ((size === 0 && !result.text && !result.tables.length) || (file && file.size === 0)) {
      warnings.push({ code: 'empty-file', message: '文件内容为空。' });
    }
    return result;
  }

  async function extractFiles(fileList) {
    var out = { text: '', tables: [], files: [], warnings: [] };
    var list = [];
    try {
      if (fileList && typeof fileList.length === 'number') {
        for (var i = 0; i < fileList.length; i++) list.push(fileList[i]);
      } else if (fileList && typeof fileList === 'object') {
        list = [fileList];
      }
    } catch (e) {
      list = [];
    }
    if (!list.length) {
      out.warnings.push({ code: 'no-files', message: '未选择任何文件。' });
      return out;
    }
    var accepted = list.slice(0, MAX_FILES);
    if (list.length > MAX_FILES) {
      out.warnings.push({
        code: 'too-many-files',
        message: '最多支持 ' + MAX_FILES + ' 个文件，已忽略其余 ' + (list.length - MAX_FILES) + ' 个。'
      });
    }
    var parts = [];
    var tables = [];
    for (var f = 0; f < accepted.length; f++) {
      var file = accepted[f];
      var res;
      try {
        res = await extractFile(file);
      } catch (err) {
        res = {
          name: (file && file.name) || 'file',
          ext: extOf((file && file.name) || ''),
          size: 0,
          text: '',
          tables: [],
          warnings: [{ code: 'read-failed', message: '读取文件失败：' + (err && err.message ? err.message : '未知错误') }]
        };
      }
      (res.warnings || []).forEach(function (w) {
        out.warnings.push({ code: w.code, message: w.message, file: res.name });
      });
      out.files.push({
        name: res.name,
        ext: res.ext,
        size: res.size,
        chars: res.text.length,
        excerpt: makeExcerpt(res.text)
      });
      if (res.text) parts.push('===== FILE: ' + res.name + ' =====\n' + res.text);
      if (res.tables && res.tables.length) {
        for (var t = 0; t < res.tables.length; t++) {
          if (Array.isArray(res.tables[t])) tables.push(res.tables[t]);
        }
        tables.push([]);
      }
    }
    var combined = parts.join('\n\n');
    if (combined.length > MAX_TEXT_CHARS) {
      combined = combined.slice(0, MAX_TEXT_CHARS);
      out.warnings.push({ code: 'text-truncated', message: '合并文本超过 300,000 字符，已截断。' });
    }
    out.text = combined;
    out.tables = tables;
    if (!combined.trim()) {
      out.warnings.push({ code: 'no-text', message: '所选文件中没有可识别的文字。' });
    }
    return out;
  }

